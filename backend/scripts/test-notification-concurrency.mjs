import prisma from "../src/lib/prisma.js";
import { generateForecastNotifications } from "../src/services/notification.service.js";

const USER_ID = "cmsbi0qat0000l8kse16ou29u";
const TEST_ID = `concurrency-${Date.now()}`;
const TEST_TITLE = `Concurrency Test ${Date.now()}`;
const TEST_METRIC = TEST_ID;
const TEST_DATE = new Date("2099-01-01T00:00:00.000Z");

const businessInsights = {
  riskAlerts: [
    {
      level: "medium",
      type: TEST_ID,
      title: TEST_TITLE,
      message: "Concurrency deduplication test notification.",
    },
  ],
  recommendations: [],
};

const forecastExplainability = [];

async function main() {
  console.log("\n=== NOTIFICATION CONCURRENCY TEST ===\n");

  // Verify user exists.
  const user = await prisma.user.findUnique({
    where: { id: USER_ID },
    select: {
      id: true,
      email: true,
    },
  });

  if (!user) {
    throw new Error(`User ${USER_ID} was not found.`);
  }

  console.log("✓ User:", user.email);

  // Remove only previous records generated by this test ID.
  await prisma.notification.deleteMany({
    where: {
      userId: USER_ID,
      relatedMetric: TEST_METRIC,
    },
  });

  console.log("✓ Previous test records cleared");

  // Run two notification-generation operations concurrently.
  console.log("\nStarting two concurrent notification generations...");

  const [resultA, resultB] = await Promise.all([
    generateForecastNotifications({
      userId: USER_ID,
      businessInsights,
      forecastExplainability,
    }),
    generateForecastNotifications({
      userId: USER_ID,
      businessInsights,
      forecastExplainability,
    }),
  ]);

  console.log("\nResult A:");
  console.log(JSON.stringify(resultA, null, 2));

  console.log("\nResult B:");
  console.log(JSON.stringify(resultB, null, 2));

  // Inspect exactly the records belonging to this test.
  const matchingNotifications =
    await prisma.notification.findMany({
      where: {
        userId: USER_ID,
        relatedMetric: TEST_METRIC,
      },
      orderBy: {
        createdAt: "asc",
      },
      select: {
        id: true,
        type: true,
        priority: true,
        title: true,
        message: true,
        relatedMetric: true,
        relatedDate: true,
        createdAt: true,
      },
    });

  console.log(
    "\nMatching notifications:",
    matchingNotifications.length
  );

  for (const notification of matchingNotifications) {
    console.log(
      JSON.stringify(notification, null, 2)
    );
  }

  const createdTotal =
  (resultA?.created?.length || 0) +
  (resultB?.created?.length || 0);

const skippedTotal =
  (resultA?.skipped?.length || 0) +
  (resultB?.skipped?.length || 0);

  console.log("\nSummary:");
  console.log("Concurrent calls: 2");
  console.log("Total created:", createdTotal);
  console.log("Total skipped:", skippedTotal);
  console.log(
    "Matching DB notifications:",
    matchingNotifications.length
  );

  // The core concurrency assertion.
  if (createdTotal !== 1) {
    throw new Error(
      `FAIL: Expected exactly 1 notification to be created, got ${createdTotal}.`
    );
  }

  if (matchingNotifications.length !== 1) {
    throw new Error(
      `FAIL: Expected exactly 1 matching DB notification, got ${matchingNotifications.length}.`
    );
  }

  console.log(
    "\n✓ CONCURRENCY DEDUPLICATION PASSED"
  );
  console.log(
    "✓ Two concurrent calls produced exactly one notification."
  );

  // Clean up the test record.
  await prisma.notification.deleteMany({
    where: {
      userId: USER_ID,
      relatedMetric: TEST_METRIC,
    },
  });

  console.log("✓ Test notification cleaned up");
}

main()
  .catch((error) => {
    console.error(
      "\n=== CONCURRENCY TEST FAILED ==="
    );
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });